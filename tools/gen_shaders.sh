#!/bin/bash
# Compile gpu/shaders/*.vert|frag to SPIR-V and write gpu/vkr_shaders.h,
# which gpu/vkr.c embeds. The header is committed, so builds don't need a
# shader compiler; run this (make shaders) after changing a shader.
# Needs glslangValidator (apt install glslang-tools).
set -e
cd "$(dirname "$0")/.."
out=gpu/vkr_shaders.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "/* Generated by tools/gen_shaders.sh from gpu/shaders/: do not edit. */"
    for f in gpu/shaders/*.vert gpu/shaders/*.frag; do
        name=$(basename "$f" | tr . _)_spv
        glslangValidator -V --target-env vulkan1.0 --quiet --vn "$name" -o "$tmp/$name.h" "$f" >&2
        grep -vE '^[[:space:]]*(//|#pragma)' "$tmp/$name.h" | sed 's/^const uint32_t/static const uint32_t/'
    done
} > "$tmp/all.h"
mv "$tmp/all.h" "$out"
echo "wrote $out"
