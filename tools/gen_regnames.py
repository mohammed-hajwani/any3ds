"""Generate gpu/regnames.c: PICA register names (names and ids only) taken
from libctru's registers.h, for GPU_TRACE output."""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
names = {}
for line in open(src, encoding='utf-8'):
    m = re.match(r'#define GPUREG_(\w+)\s+(0x[0-9A-Fa-f]+)', line)
    if not m:
        continue
    name, value = m[1], int(m[2], 16)
    if re.fullmatch(r'[0-9A-F]{4}', name):      # GPUREG_0123: unnamed
        continue
    names.setdefault(value, name)

out = ['/* Generated by tools/gen_regnames.py from libctru\'s gpu/registers.h:',
       '   the PICA register names (ids and names only), for GPU_TRACE. */',
       '#include "pica.h"', '',
       'const char *const pica_reg_names[PICA_REGS] = {']
for value in sorted(names):
    out.append(f'    [0x{value:03x}] = "{names[value]}",')
out += ['};', '']
open(dst, 'w', newline='\n').write('\n'.join(out))
print(len(names), 'names')
