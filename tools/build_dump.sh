#!/bin/sh
# Recompile and build your own decrypted dump (a .3ds, .cxi, or a folder with
# code.bin + exheader.bin) into a host program that runs it on our HLE.
#
#   tools/build_dump.sh DUMP [OUT_DIR]        (default OUT_DIR: out/dump)
#   OUT_DIR/run --romfs DUMP --dump frame.bmp ...   (options: tests/m6/runner.c)
#   OS_ONLY=1 tools/build_dump.sh DUMP          rebuild only the OS layer (after hle/ changes)
#
# The main program and every CRO module in the RomFS (the game's "DLLs",
# loaded at run time through ldr:ro) are recompiled; a module's code is
# relative to the address the game will load it at.
#
# Everything generated stays in OUT_DIR, under out/ (gitignored): recompiled
# game code must never be committed. Functions the translator can't handle
# yet become stubs that stop loudly if called (--keep-going); they are listed
# in OUT_DIR/*.failures.txt.
set -eu
dump=${1:?usage: tools/build_dump.sh DUMP [OUT_DIR]}
out=${2:-out/dump}
case "$out" in out/*) ;; *) echo "OUT_DIR must be under out/ (gitignored)"; exit 1 ;; esac
jobs=$(nproc)
mkdir -p "$out" "$out/cro"
py=.venv/bin/python
start=$(date +%s)
since() { echo "   ($(( $(date +%s) - start )) s so far)"; }

# OS_ONLY=1: keep the recompiled game, rebuild just the OS layer (hle/, gpu/).
if [ "${OS_ONLY:-0}" = 1 ] && [ -f "$out/gen.o" ]; then
    echo "== keeping the recompiled game in $out (OS_ONLY=1)"
else
    echo "== recompiling $dump"
    rm -f "$out"/gen*.c "$out"/gen*.o "$out"/cro/*
    $py -m recomp "$dump" -o "$out/gen.c" --keep-going --split 400 > "$out/recomp.log"
    grep -v '^  f_' "$out/recomp.log"
    since

    # The CRO modules, if the game has any.
    $py -m recomp.romfs "$dump" 2>/dev/null | awk '$2 ~ /\.cro$/ { print $2 }' > "$out/cro/list.txt" || true
    if [ -s "$out/cro/list.txt" ]; then
        echo "== recompiling $(wc -l < "$out/cro/list.txt") CRO modules with $jobs jobs"
        xargs -P "$jobs" -I{} sh -c '
            name=$(basename "{}" .cro)
            '"$py"' -m recomp "'"$dump"'" --cro "{}" -o "'"$out"'/cro/$name.c" --keep-going --split 400 \
                > "'"$out"'/cro/$name.log" 2>&1 || { echo "  FAILED: {} (see '"$out"'/cro/$name.log)"; exit 1; }
        ' < "$out/cro/list.txt"
        grep -h "^module " "$out"/cro/*.log | awk '{ f += $3; i += $5 } END { print "   ", f, "functions,", i, "instructions" }'
        since
    fi
    # The table of modules the runtime looks up when the game loads one.
    {
        echo '/* Generated by tools/build_dump.sh: the recompiled CRO modules. */'
        echo '#include "context.h"'
        for m in $(cat "$out"/cro/*.module 2>/dev/null); do echo "extern const RecompModule recomp_module_$m;"; done
        echo 'const RecompModule *const *recomp_module_table(void)'
        echo '{'
        echo '    static const RecompModule *const modules[] = {'
        for m in $(cat "$out"/cro/*.module 2>/dev/null); do echo "        &recomp_module_$m,"; done
        echo '        NULL,'
        echo '    };'
        echo '    return modules;'
        echo '}'
    } > "$out/modules.c"
fi

# Generated code: unoptimised and without sanitizers, or a big game takes
# hours to compile. The OS layer is optimised a little: it runs every frame.
GEN_FLAGS="-std=c11 -O0 -g0 -w -fno-math-errno -Iruntime"
OS_FLAGS="-std=c11 -O1 -g -Wall -Wextra -fno-math-errno -Iruntime -Ihle -Igpu -pthread"

if [ "${OS_ONLY:-0}" != 1 ] || [ ! -f "$out/gen.o" ]; then
    echo "== compiling $(ls "$out"/gen*.c "$out"/cro/*.c "$out/modules.c" 2>/dev/null | wc -l) C files with $jobs jobs"
    ls "$out"/gen*.c "$out"/cro/*.c "$out/modules.c" 2>/dev/null \
        | xargs -P "$jobs" -I{} sh -c 'clang '"$GEN_FLAGS"' -c {} -o "$(echo {} | sed "s/\.c$/.o/")"'
    since
fi
for f in tests/m6/runner.c runtime/runtime.c hle/*.c gpu/*.c; do
    echo "$f"
done | xargs -P "$jobs" -I{} sh -c 'clang '"$OS_FLAGS"' -c {} -o '"$out"'/os_$(basename {} .c).o'

echo "== linking $out/run"
clang -pthread "$out"/gen*.o "$out"/cro/*.o "$out/modules.o" "$out"/os_*.o -lm -o "$out/run"
echo "built $out/run"
since
