"""Write translated functions, the program image and symbol tables as C."""

import re


def c_name(addr):
    return f'f_{addr:08x}'


def _bytes_array(name, data):
    lines = [f'static const uint8_t {name}[{max(len(data), 1)}] = {{']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    lines.append('};')
    return lines


def _c_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def emit(functions, header_name, program=None, trace=False, split=None):
    """`functions` is a list of translate.TranslatedFunction.

    With trace=True, every instruction first calls RECOMP_TRACE(addr, text)
    so a test driver can compare state against a reference CPU (M3).

    Returns (c_source, header_source). With split=N, the functions go into
    extra files of N functions each, so a big program compiles in parallel:
    returns ([main source, chunk sources...], header_source); the main
    source keeps the tables and the program image.
    """
    prologue = ['/* Generated by recomp. Do not edit. */']
    if trace:
        prologue.append('#define RECOMP_TRACING 1   /* built with --trace */')
    prologue += [f'#include "{header_name}"', '']
    c = list(prologue)
    chunks = []
    if split:
        for i in range(0, len(functions), split):
            chunk = list(prologue)
            _emit_functions(chunk, functions[i:i + split], trace)
            chunks.append('\n'.join(chunk) + '\n')
    else:
        _emit_functions(c, functions, trace)
    h = _tables(c, functions, header_name, program)
    if split:
        return ['\n'.join(c) + '\n'] + chunks, h
    return '\n'.join(c) + '\n', h


def _emit_functions(c, functions, trace):
    for tf in functions:
        c.append(f'/* {tf.fn.name} */')
        c.append(f'void {c_name(tf.fn.addr)}(Ctx *ctx)')
        c.append('{')
        if tf.uses_ret:
            c.append('    const uint32_t ret = ctx->r[14];  /* return address we were called with */')
        for addr, comment, lines in tf.body:
            if addr in tf.labels:
                c.append(f'L_{addr:08x}: ;')
            c.append(f'    /* {comment} */')
            if trace and lines:
                c.append(f'    RECOMP_TRACE(0x{addr:08x}u, {_c_string(comment.split(": ", 1)[1])});')
            c.extend(f'    {line}' for line in lines)
        c.append('}')
        c.append('')


def _tables(c, functions, header_name, program):
    """Append the symbol tables and program image to `c`; return the header."""
    # Addresses carry the Thumb bit (bit 0), like ELF symbols and like a
    # real `bx` target.
    c.append('const RecompSym recomp_syms[] = {')
    for tf in functions:
        for name in [tf.fn.name] + tf.fn.aliases:
            c.append(f'    {{ "{name}", 0x{tf.fn.addr | int(tf.fn.thumb):08x}u, {c_name(tf.fn.addr)} }},')
    c.append('};')
    c.append('const size_t recomp_nsyms = sizeof recomp_syms / sizeof recomp_syms[0];')
    c.append('')
    c.append('GuestFn recomp_lookup(const char *name)')
    c.append('{')
    c.append('    for (size_t i = 0; i < recomp_nsyms; i++)')
    c.append('        if (strcmp(recomp_syms[i].name, name) == 0)')
    c.append('            return recomp_syms[i].fn;')
    c.append('    return NULL;')
    c.append('}')
    c.append('')

    entry = program.entry if program and program.entry is not None else 0
    c.append(f'const uint32_t recomp_entry = 0x{entry:08x}u;  /* ELF entry point (0: none) */')
    c.append('')

    # Entry address -> function, sorted, for indirect calls (recomp_call).
    c.append('static const struct { uint32_t addr; GuestFn fn; } by_addr[] = {')
    for tf in sorted(functions, key=lambda tf: tf.fn.addr | int(tf.fn.thumb)):
        c.append(f'    {{ 0x{tf.fn.addr | int(tf.fn.thumb):08x}u, {c_name(tf.fn.addr)} }},  /* {tf.fn.name} */')
    c.append('};')
    c.append('')
    c.append('GuestFn recomp_find(uint32_t addr)')
    c.append('{')
    c.append('    size_t lo = 0, hi = sizeof by_addr / sizeof by_addr[0];')
    c.append('    while (lo < hi) {       /* binary search */')
    c.append('        size_t mid = lo + (hi - lo) / 2;')
    c.append('        if (by_addr[mid].addr == addr) return by_addr[mid].fn;')
    c.append('        if (by_addr[mid].addr < addr) lo = mid + 1; else hi = mid;')
    c.append('    }')
    c.append('    return NULL;')
    c.append('}')
    c.append('')

    # The program image: every loadable segment, copied to its guest address.
    segments = program.segments if program else []
    for seg in segments:
        c.extend(_bytes_array(f'seg_{seg.vaddr:08x}', seg.data))
        c.append('')
    c.append('const RecompSegment recomp_segments[] = {')
    for seg in segments:
        c.append(f'    {{ 0x{seg.vaddr:08x}u, {seg.memsz} }},')
    c.append('    { 0, 0 },')
    c.append('};')
    c.append('')
    c.append('void recomp_load_image(uint8_t *mem)')
    c.append('{')
    if not segments:
        c.append('    (void)mem;')
    for seg in segments:
        name = f'seg_{seg.vaddr:08x}'
        kind = 'rw' if seg.writable else 'ro'
        c.append(f'    memcpy(mem + 0x{seg.vaddr:08x}u, {name}, {len(seg.data)});  /* {kind} */')
        if seg.memsz > len(seg.data):
            c.append(f'    memset(mem + 0x{seg.vaddr + len(seg.data):08x}u, 0, {seg.memsz - len(seg.data)});  /* .bss */')
    c.append('}')
    c.append('')

    # Data symbols, so tools and harnesses can find globals by name.
    c.append('static const struct { const char *name; uint32_t addr; } data_syms[] = {')
    for name, addr in sorted((program.data_symbols if program else {}).items()):
        c.append(f'    {{ "{name}", 0x{addr:08x}u }},')
    c.append('    { NULL, 0 },')
    c.append('};')
    c.append('')
    c.append('uint32_t recomp_data_lookup(const char *name)')
    c.append('{')
    c.append('    for (size_t i = 0; data_syms[i].name; i++)')
    c.append('        if (strcmp(data_syms[i].name, name) == 0)')
    c.append('            return data_syms[i].addr;')
    c.append('    return 0;')
    c.append('}')

    guard = 'RECOMP_' + re.sub(r'\W', '_', header_name).upper()
    h = [
        '/* Generated by recomp. Do not edit. */',
        f'#ifndef {guard}',
        f'#define {guard}',
        '',
        '#include "context.h"',
        '',
    ]
    h.extend(f'void {c_name(tf.fn.addr)}(Ctx *ctx);  /* {tf.fn.name} */' for tf in functions)
    h.append('')
    h.append('#endif')

    return '\n'.join(h) + '\n'
