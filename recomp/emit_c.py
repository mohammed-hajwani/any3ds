"""Write translated functions, the program image and symbol tables as C."""

import re


def c_name(addr):
    return f'f_{addr:08x}'


def _bytes_array(name, data):
    lines = [f'static const uint8_t {name}[{max(len(data), 1)}] = {{']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    lines.append('};')
    return lines


def _c_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def emit(functions, header_name, program=None, trace=False):
    """`functions` is a list of translate.TranslatedFunction.

    With trace=True, every instruction first calls RECOMP_TRACE(addr, text)
    so a test driver can compare state against a reference CPU (M3).

    Returns (c_source, header_source).
    """
    c = ['/* Generated by recomp. Do not edit. */']
    if trace:
        c.append('#define RECOMP_TRACING 1   /* built with --trace */')
    c += [f'#include "{header_name}"', '']
    for tf in functions:
        c.append(f'/* {tf.fn.name} */')
        c.append(f'void {c_name(tf.fn.addr)}(Ctx *ctx)')
        c.append('{')
        if tf.uses_ret:
            c.append('    const uint32_t ret = ctx->r[14];  /* return address we were called with */')
        for addr, comment, lines in tf.body:
            if addr in tf.labels:
                c.append(f'L_{addr:08x}:')
            c.append(f'    /* {comment} */')
            if trace and lines:
                c.append(f'    RECOMP_TRACE(0x{addr:08x}u, {_c_string(comment.split(": ", 1)[1])});')
            c.extend(f'    {line}' for line in lines)
        c.append('}')
        c.append('')

    c.append('const RecompSym recomp_syms[] = {')
    for tf in functions:
        c.append(f'    {{ "{tf.fn.name}", 0x{tf.fn.addr:08x}u, {c_name(tf.fn.addr)} }},')
    c.append('};')
    c.append('const size_t recomp_nsyms = sizeof recomp_syms / sizeof recomp_syms[0];')
    c.append('')
    c.append('GuestFn recomp_lookup(const char *name)')
    c.append('{')
    c.append('    for (size_t i = 0; i < recomp_nsyms; i++)')
    c.append('        if (strcmp(recomp_syms[i].name, name) == 0)')
    c.append('            return recomp_syms[i].fn;')
    c.append('    return NULL;')
    c.append('}')
    c.append('')

    # The program image: every loadable segment, copied to its guest address.
    segments = program.segments if program else []
    for seg in segments:
        c.extend(_bytes_array(f'seg_{seg.vaddr:08x}', seg.data))
        c.append('')
    c.append('const RecompSegment recomp_segments[] = {')
    for seg in segments:
        c.append(f'    {{ 0x{seg.vaddr:08x}u, {seg.memsz} }},')
    c.append('    { 0, 0 },')
    c.append('};')
    c.append('')
    c.append('void recomp_load_image(uint8_t *mem)')
    c.append('{')
    if not segments:
        c.append('    (void)mem;')
    for seg in segments:
        name = f'seg_{seg.vaddr:08x}'
        kind = 'rw' if seg.writable else 'ro'
        c.append(f'    memcpy(mem + 0x{seg.vaddr:08x}u, {name}, {len(seg.data)});  /* {kind} */')
        if seg.memsz > len(seg.data):
            c.append(f'    memset(mem + 0x{seg.vaddr + len(seg.data):08x}u, 0, {seg.memsz - len(seg.data)});  /* .bss */')
    c.append('}')
    c.append('')

    # Data symbols, so tools and harnesses can find globals by name.
    c.append('static const struct { const char *name; uint32_t addr; } data_syms[] = {')
    for name, addr in sorted((program.data_symbols if program else {}).items()):
        c.append(f'    {{ "{name}", 0x{addr:08x}u }},')
    c.append('    { NULL, 0 },')
    c.append('};')
    c.append('')
    c.append('uint32_t recomp_data_lookup(const char *name)')
    c.append('{')
    c.append('    for (size_t i = 0; data_syms[i].name; i++)')
    c.append('        if (strcmp(data_syms[i].name, name) == 0)')
    c.append('            return data_syms[i].addr;')
    c.append('    return 0;')
    c.append('}')

    guard = 'RECOMP_' + re.sub(r'\W', '_', header_name).upper()
    h = [
        '/* Generated by recomp. Do not edit. */',
        f'#ifndef {guard}',
        f'#define {guard}',
        '',
        '#include "context.h"',
        '',
    ]
    h.extend(f'void {c_name(tf.fn.addr)}(Ctx *ctx);  /* {tf.fn.name} */' for tf in functions)
    h.append('')
    h.append('#endif')

    return '\n'.join(c) + '\n', '\n'.join(h) + '\n'
